# ============================================================================
# Helper Functions
# ============================================================================


def get_static_metadata(model_name: str) -> Optional[Dict[str, Any]]:
    """Get static metadata for a model if available.

    Args:
        model_name: Name of the Earth2Studio model class

    Returns:
        Metadata dict with 'variables', 'lead_times', etc. or None if
        the model requires dynamic loading.
    """
    # Check for exact match first
    if model_name in STATIC_MODEL_METADATA:
        return STATIC_MODEL_METADATA[model_name]

    # Check for Pangu variants (Pangu6, Pangu24, PanguBase all use same vars)
    if model_name.startswith("Pangu"):
        return STATIC_MODEL_METADATA.get("Pangu6")

    return None


def requires_dynamic_loading(model_name: str) -> bool:
    """Check if a model requires dynamic loading for metadata.

    Args:
        model_name: Name of the Earth2Studio model class

    Returns:
        True if the model must be instantiated to get metadata.
    """
    return model_name in DYNAMIC_METADATA_MODELS


def get_all_static_model_names() -> List[str]:
    """Get list of all models with static metadata available.

    Returns:
        List of model names that have static metadata.
    """
    return list(STATIC_MODEL_METADATA.keys())


def get_model_variables(model_name: str) -> Optional[List[str]]:
    """Get input variables for a model (if static metadata available).

    Args:
        model_name: Name of the Earth2Studio model class

    Returns:
        List of input variable names or None if not available.
    """
    meta = get_static_metadata(model_name)
    if meta:
        return meta.get("variables", [])
    return None


def get_model_lead_times(model_name: str) -> Optional[List[int]]:
    """Get lead times for a model (if static metadata available).

    Args:
        model_name: Name of the Earth2Studio model class

    Returns:
        List of lead times in hours or None if not available.
    """
    meta = get_static_metadata(model_name)
    if meta:
        return meta.get("lead_times", [])
    return None
